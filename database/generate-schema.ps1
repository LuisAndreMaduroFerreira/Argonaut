# Rebuilds database\schema.sql: the whole schema as one file, for setting up a database from
# scratch without running the API first. It applies server\migrations to a throwaway database
# in the running argonaut-db container, exactly as the API would, and dumps the result.
#
# Run it after adding a migration. server\test\schema-file.test.mjs fails while schema.sql and
# the migrations disagree.
#
#   .\database\generate-schema.ps1

$ErrorActionPreference = 'Stop'

$root = Split-Path $PSScriptRoot -Parent
$container = 'argonaut-db'
$scratch = 'argonaut_schema_build'
$output = Join-Path $PSScriptRoot 'schema.sql'

function Invoke-Psql([string]$database, [string[]]$arguments) {
    & docker exec $container psql -U argonaut -d $database -v ON_ERROR_STOP=1 -q @arguments
    if ($LASTEXITCODE -ne 0) { throw "psql failed in $database" }
}

$running = & docker inspect -f '{{.State.Running}}' $container 2>$null
if ($running -ne 'true') { throw "The $container container isn't running. Start it with: docker compose up -d argonaut-db" }

Invoke-Psql 'postgres' @('-c', "DROP DATABASE IF EXISTS $scratch WITH (FORCE)", '-c', "CREATE DATABASE $scratch")
try {
    & docker exec $container rm -rf /tmp/argonaut-schema
    & docker cp (Join-Path $root 'server\migrations') "${container}:/tmp/argonaut-schema"
    if ($LASTEXITCODE -ne 0) { throw 'Copying the migrations into the container failed' }

    # The same bookkeeping table and the same order as migrate() in server\src\db.ts.
    Invoke-Psql $scratch @('-c', 'CREATE TABLE IF NOT EXISTS schema_migrations (name TEXT PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL DEFAULT now())')
    $migrations = Get-ChildItem (Join-Path $root 'server\migrations') -Filter '*.sql' |
        Where-Object { $_.Name -match '^\d{4}_[\w-]+\.sql$' } | Sort-Object Name
    foreach ($migration in $migrations) {
        Invoke-Psql $scratch @('-1', '-f', "/tmp/argonaut-schema/$($migration.Name)",
            '-c', "INSERT INTO schema_migrations (name) VALUES ('$($migration.Name)')")
    }

    & docker exec $container pg_dump -U argonaut -d $scratch --schema-only --no-owner --no-privileges -f /tmp/argonaut-schema/dump.sql
    if ($LASTEXITCODE -ne 0) { throw 'pg_dump failed' }
    $dumpFile = Join-Path ([System.IO.Path]::GetTempPath()) 'argonaut-schema-dump.sql'
    & docker cp "${container}:/tmp/argonaut-schema/dump.sql" $dumpFile
    $dump = [System.IO.File]::ReadAllText($dumpFile, [System.Text.Encoding]::UTF8)
    Remove-Item $dumpFile

    # \restrict and \unrestrict carry a random key that changes on every dump; leave them out
    # so the file only changes when the schema does.
    $dump = ($dump -split "`n" | Where-Object { $_ -notmatch '^\\(un)?restrict ' }) -join "`n"
    $names = ($migrations | ForEach-Object { "  ('$($_.Name)')" }) -join ",`n"

    $header = @"
-- Argonaut's database schema, from scratch: every table, index and constraint, as of the
-- migrations listed at the end. Generated by database\generate-schema.ps1 from
-- server\migrations; don't edit it by hand.
--
-- Load it into an empty database owned by the app's user (database\install-database.ps1 does
-- this). The API normally builds the same schema itself on first start, so with Docker you
-- never need this file.

"@
    $footer = @"

-- The migrations this schema already contains, so the API doesn't run them again.
INSERT INTO public.schema_migrations (name) VALUES
$names;
"@
    $text = ($header + $dump.Trim() + "`n" + $footer).Replace("`r`n", "`n")
    [System.IO.File]::WriteAllText($output, $text, (New-Object System.Text.UTF8Encoding $false))
    Write-Host "Wrote $output ($($migrations.Count) migrations)"
}
finally {
    & docker exec $container rm -rf /tmp/argonaut-schema
    Invoke-Psql 'postgres' @('-c', "DROP DATABASE IF EXISTS $scratch WITH (FORCE)")
}
